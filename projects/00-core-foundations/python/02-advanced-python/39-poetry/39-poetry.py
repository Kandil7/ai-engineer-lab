def _verify() -> None:
    """Self-check. Silent on failure-free completion when run with --verify."""
    # Constraint table, straight from the Poetry docs.
    assert expand_constraint("^1.2.3") == (">=1.2.3", "<2.0.0")
    assert expand_constraint("^1.2") == (">=1.2.0", "<2.0.0")
    assert expand_constraint("^1") == (">=1.0.0", "<2.0.0")
    assert expand_constraint("^0.2.3") == (">=0.2.3", "<0.3.0")
    assert expand_constraint("^0.0.3") == (">=0.0.3", "<0.0.4")
    assert expand_constraint("^0.0") == (">=0.0.0", "<0.1.0")
    assert expand_constraint("^0") == (">=0.0.0", "<1.0.0")
    assert expand_constraint("~1.2.3") == (">=1.2.3", "<1.3.0")
    assert expand_constraint("~1.2") == (">=1.2.0", "<1.3.0")
    assert expand_constraint("~1") == (">=1.0.0", "<2.0.0")
    assert expand_constraint("1.2.3") == ("==1.2.3", "")
    assert expand_constraint("*") == (">=0.0.0", "")
    assert expand_constraint("1.*") == (">=1.0.0", "<2.0.0")
    assert expand_constraint("1.2.*") == (">=1.2.0", "<1.3.0")
    assert expand_constraint("~=1.2.3") == (">=1.2.3", "<1.3.0")
    assert expand_constraint("~=1.2") == (">=1.2.0", "<2.0.0")
    assert expand_constraint(">=1.26,<3.0.0") == (">=1.26", "<3.0.0")

    # Membership.
    low, high = expand_constraint("^0.2.3")
    assert version_in_bounds("0.2.9", (low, high))
    assert not version_in_bounds("0.3.0", (low, high))
    assert version_in_bounds("1.26.4", (">=1.26", "<3.0.0"))
    assert not version_in_bounds("3.0.0", (">=1.26", "<3.0.0"))

    # Requirement parsing.
