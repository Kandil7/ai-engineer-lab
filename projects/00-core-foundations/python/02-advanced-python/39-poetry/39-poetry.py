def classify_manifest(data: dict) -> dict:
    """Report which metadata tables a pyproject.toml uses and where it clashes."""
    project = data.get("project", {})
    poetry = data.get("tool", {}).get("poetry", {})
    pep621_deps = list(project.get("dependencies", []))
    poetry_deps = set(poetry.get("dependencies", {}))
    pep621_names = {parse_requirement(d)[0].lower() for d in pep621_deps}
    return {
        "uses_pep621": bool(project),
        "uses_poetry_table": bool(poetry),
        "pep621_deps": pep621_deps,
        "poetry_groups": sorted(poetry.get("group", {})),
        "pep735_groups": sorted(data.get("dependency-groups", {})),
        "dupes": sorted(pep621_names & {n.lower() for n in poetry_deps}),
    }


# --------------------------------------------------------------------------- #
# Section 2: constraint expansion
# --------------------------------------------------------------------------- #
# Poetry constraint syntax (tool.poetry tables) vs PEP 508 (project table).
#   ^1.2.3 -> >=1.2.3,<2.0.0   (caret: leftmost non-zero digit may not bump)
#   ~1.2.3 -> >=1.2.3,<1.3.0   (tilde: only patch may bump)
#   1.2.3  -> ==1.2.3          (bare version is EXACT, not caret)
#   1.2.*  -> >=1.2.0,<1.3.0   (wildcard)
#   ~=1.2.3-> >=1.2.3,<1.3.0   (PEP 440 compatible release)
_OPERATORS = ("===", "==", "!=", ">=", "<=", "~=", ">", "<")


def _split_op(clause: str) -> tuple[str, str]:
    """Split '<operator><version>' into (operator, version)."""
    text = clause.strip()
    for op in _OPERATORS:
        if text.startswith(op):
            return op, text[len(op) :].strip()
    return "", text


def _nums(version: str) -> list[int]:
    """Parse the numeric prefix of a version into ints ('' parts skipped)."""
    core = ""
    for ch in version.strip():
        if ch.isdigit() or ch == ".":
            core += ch
        else:
            break
    return [int(p) for p in core.split(".") if p]


def _pad(parts: list[int], width: int = 3) -> list[int]:
    """Pad a version component list with zeros up to `width`."""
    return parts + [0] * (width - len(parts))


def _caret(version: str) -> tuple[str, str]:
    """^1.2.3 -> >=1.2.3,<2.0.0 ; ^0.2.3 -> >=0.2.3,<0.3.0 ; ^0 -> >=0.0.0,<1.0.0."""
    parts = _nums(version)
    if not parts:
        raise ValueError(f"bad caret constraint: ^{version}")
    low = ".".join(str(p) for p in _pad(parts))
    if parts[0] > 0:
        high = f"{parts[0] + 1}.0.0"
    elif len(parts) == 1:
        high = "1.0.0"
    elif len(parts) == 2:
        high = f"0.{parts[1] + 1}.0" if parts[1] > 0 else "0.1.0"
    elif parts[1] > 0:
        high = f"0.{parts[1] + 1}.0"
    elif parts[2] > 0:
        high = f"0.0.{parts[2] + 1}"
    else:
        high = "0.0.1"
    return (f">={low}", f"<{high}")


def _tilde(version: str) -> tuple[str, str]:
    """~1.2.3 -> >=1.2.3,<1.3.0 ; ~1.2 -> >=1.2.0,<1.3.0 ; ~1 -> >=1.0.0,<2.0.0."""
    parts = _nums(version)
    if not parts:
        raise ValueError(f"bad tilde constraint: ~{version}")
    low = ".".join(str(p) for p in _pad(parts))
    if len(parts) == 1:
        high = f"{parts[0] + 1}.0.0"
    else:
        high = f"{parts[0]}.{parts[1] + 1}.0"
    return (f">={low}", f"<{high}")


def _compatible(version: str) -> tuple[str, str]:
    """~=1.2.3 -> >=1.2.3,<1.3.0 ; ~=1.2 -> >=1.2.0,<2.0.0 (PEP 440)."""
    parts = _nums(version)
    if len(parts) < 2:
        raise ValueError(f"~= needs at least two components: ~= {version}")
    low = ".".join(str(p) for p in _pad(parts))
    if len(parts) == 2:
        high = f"{parts[0] + 1}.0.0"
    else:
        high = f"{parts[0]}.{parts[1] + 1}.0"
    return (f">={low}", f"<{high}")


def _wildcard(spec: str) -> tuple[str, str]:
    """'*' -> >=0.0.0 ; '1.*' -> >=1.0.0,<2.0.0 ; '1.2.*' -> >=1.2.0,<1.3.0."""
    base = spec.split("*")[0].strip().rstrip(".")
    parts = _nums(base) if base else []
    if not parts:
        return (">=0.0.0", "")
    low = ".".join(str(p) for p in _pad(parts))
    if len(parts) == 1:
        return (f">={low}", f"<{parts[0] + 1}.0.0")
    return (f">={low}", f"<{parts[0]}.{parts[1] + 1}.0")


def expand_constraint(spec: str) -> tuple[str, str]:
    """Expand a constraint into a (lower, upper) pair of PEP 508 specifiers.

    An empty string means 'unbounded on that side'. Raises on operators the
    teaching expander does not model (!=, ===).
    """
    text = spec.strip()
    if not text:
        return ("", "")
    if text.startswith("^"):
        return _caret(text[1:])
    if text.startswith("~="):
        return _compatible(text[2:])
    if text.startswith("~"):
        return _tilde(text[1:])
    if "*" in text:
        return _wildcard(text)
    if "," in text:
        lower, upper = "", ""
        for clause in (c.strip() for c in text.split(",")):
            op, version = _split_op(clause)
            if op in (">=", ">"):
                lower = f"{op}{version}"
            elif op in ("<", "<="):
                upper = f"{op}{version}"
            elif op == "==":
                lower = clause
            else:
                raise ValueError(f"unsupported clause in range: {clause!r}")
        return (lower, upper)
    op, version = _split_op(text)
    if op == "" or op == "==":
        return (f"=={version}", "")
    if op in (">=", ">"):
        return (f"{op}{version}", "")
    if op in ("<", "<="):
        return ("", f"{op}{version}")
    raise ValueError(f"unsupported constraint: {spec!r}")


def _vkey(version: str) -> tuple[int, ...]:
    """Comparable 4-tuple for a version string (prerelease suffixes dropped)."""
    return tuple(_pad(_nums(version), 4))


def version_in_bounds(version: str, bounds: tuple[str, str]) -> bool:
    """True when `version` satisfies the (lower, upper) pair."""
    lower, upper = bounds
    value = _vkey(version)
    if lower:
        op, bound = _split_op(lower)
        target = _vkey(bound)
        if op == "==":
            if value != target:
                return False
        elif op == ">=":
            if not value >= target:
                return False
        elif op == ">":
            if not value > target:
                return False
        else:
            raise ValueError(f"unsupported lower bound: {lower}")
    if upper:
        op, bound = _split_op(upper)
        target = _vkey(bound)
        if op == "<":
            if not value < target:
                return False
        elif op == "<=":
            if not value <= target:
                return False
        else:
            raise ValueError(f"unsupported upper bound: {upper}")
    return True


def parse_requirement(req: str) -> tuple[str, str, str]:
    """Split a PEP 508 requirement into (name, extras, specifier).

    Accepts both 'numpy (>=1.26,<3)' and 'numpy>=1.26,<3'.
    """
    text = req.strip()
    head, paren, rest = text.partition("(")
    if paren:
        spec = rest.rstrip(")").strip()
    else:
        spec = ""
        for i, ch in enumerate(text):
            if ch in "<>!=~@":
                head, spec = text[:i], text[i:]
                break
    extras = ""
    if "[" in head:
        name_part, _, tail = head.partition("[")
        extras = tail.strip().rstrip("]").strip()
        head = name_part
    return (head.strip(), extras, spec.strip())


# --------------------------------------------------------------------------- #
# Section 3: dependency groups vs extras, and the install flag surface
# --------------------------------------------------------------------------- #
# extras      = shipped inside the package; install with `-E name` / `--all-extras`
# groups      = development-only dependency sets; never shipped
# --with      = add an optional group
# --without   = drop a non-optional group
# --only      = install exactly these groups (overrides --with/--without)
# --all-groups= every declared group
def groups_to_install(
    groups: dict[str, bool],
    only: list[str] | None = None,
    with_groups: list[str] | None = None,
    without: list[str] | None = None,
) -> list[str]:
    """Resolve the set of groups Poetry would install for a flag combination.

    `groups` maps group name -> is_optional. 'main' (the shipped runtime deps)
    is always present and non-optional.
    """
    only = only or []
    with_groups = with_groups or []
    drop = set(without or [])
    known = set(groups)
    if only:
        selected = set(only)
    else:
        selected = {g for g, optional in groups.items() if not optional}
        selected.update(with_groups)
    unknown = (selected | drop | set(with_groups)) - known
    if unknown:
        raise ValueError(f"unknown group(s): {sorted(unknown)}")
    if only:
        return sorted(selected)
    return sorted(selected - drop)


# --------------------------------------------------------------------------- #
# Section 4: poetry.lock content-hash freshness
# --------------------------------------------------------------------------- #
# Locker.py hashes a *subset* of pyproject.toml: the manifest fields that can
# change resolution (dependencies, requires-python, sources, groups) and NOT
# unrelated tables such as [tool.ruff]. `poetry check --lock` compares this
# hash with the one stored under [metadata] in poetry.lock.
RELEVANT_PROJECT_KEYS = (
    "name",
    "version",
    "description",
    "requires-python",
    "dependencies",
    "optional-dependencies",
)
RELEVANT_POETRY_KEYS = (
    "dependencies",
    "source",
    "extras",
    "dev-dependencies",
    "group",
)


def content_hash(data: dict) -> str:
    """Mirror of Poetry's Locker content hash over the relevant manifest keys."""
    project = data.get("project", {})
    groups = data.get("dependency-groups", {})
    poetry = data.get("tool", {}).get("poetry", {})

    rel_project = {k: project[k] for k in RELEVANT_PROJECT_KEYS if k in project}
    rel_groups = dict(groups)
    rel_poetry = {k: poetry[k] for k in RELEVANT_POETRY_KEYS if k in poetry}

    relevant: dict = {}
    if rel_project:
        relevant["project"] = rel_project
    if rel_groups:
        relevant["dependency-groups"] = rel_groups
    if relevant:
        relevant["tool"] = {"poetry": rel_poetry}
    else:
        relevant = rel_poetry

    payload = json.dumps(relevant, sort_keys=True).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def lock_is_fresh(pyproject: dict, lock: dict) -> bool:
    """True when poetry.lock was generated from exactly this manifest."""
    stored = lock.get("metadata", {}).get("content-hash")
    return stored is not None and stored == content_hash(pyproject)


# --------------------------------------------------------------------------- #
# Section 5: does the lockfile satisfy the manifest?
# --------------------------------------------------------------------------- #
def unsatisfied_dependencies(pyproject: dict, lock: dict) -> list[str]:
    """Direct requirements the locked versions do not satisfy, sorted."""
    locked = {p["name"].lower(): p["version"] for p in lock.get("package", [])}
    problems: list[str] = []

    def check(name: str, spec: str) -> None:
        bounds = expand_constraint(spec)
        version = locked.get(name.lower())
        if version is None:
            problems.append(f"{name}: missing from poetry.lock")
        elif not version_in_bounds(version, bounds):
            problems.append(f"{name}: {version} outside {spec}")

    for req in pyproject.get("project", {}).get("dependencies", []):
        name, _, spec = parse_requirement(req)
        check(name, spec)
    for extra_deps in pyproject.get("project", {}).get("optional-dependencies", {}).values():
        for req in extra_deps:
            name, _, spec = parse_requirement(req)
            check(name, spec)
    poetry = pyproject.get("tool", {}).get("poetry", {})
    for group in poetry.get("group", {}).values():
        for name, constraint in group.get("dependencies", {}).items():
            spec = constraint if isinstance(constraint, str) else str(constraint.get("version", ""))
            check(name, spec)
    for reqs in pyproject.get("dependency-groups", {}).values():
        for req in reqs:
            name, _, spec = parse_requirement(req)
            check(name, spec)
    return sorted(problems)


# --------------------------------------------------------------------------- #
# Section 6: sources and priorities
# --------------------------------------------------------------------------- #
_SOURCE_PRIORITIES = {"primary", "supplemental", "explicit", "legacy"}


def source_problems(data: dict) -> list[str]:
    """Validate [[tool.poetry.source]] entries and dependency source references."""
    problems: list[str] = []
    poetry = data.get("tool", {}).get("poetry", {})
    sources = poetry.get("source", [])
    names: list[str] = []
    for src in sources:
        name = src.get("name", "")
        if not name:
            problems.append("source without a name")
            continue
        if name in names:
            problems.append(f"duplicate source name: {name}")
        names.append(name)
        priority = src.get("priority")
        if priority not in _SOURCE_PRIORITIES:
            problems.append(f"bad priority on {name}: {priority}")
    for dep, spec in poetry.get("dependencies", {}).items():
        if isinstance(spec, dict) and spec.get("source") and spec["source"] not in names:
            problems.append(f"{dep}: unknown source {spec['source']}")
    return sorted(problems)


