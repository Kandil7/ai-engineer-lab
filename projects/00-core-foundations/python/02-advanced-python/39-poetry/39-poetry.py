# --------------------------------------------------------------------------- #
# Section 8: common mistakes (reference)
# --------------------------------------------------------------------------- #
# 1. Assuming '^1.2.3' inside [project] dependencies means >=1.2.3,<2.0.0.
#    PEP 508 rejects it; use '>=1.2.3,<2.0.0'. Poetry converts on `poetry add`.
# 2. Assuming a bare '1.2.3' in [tool.poetry.dependencies] is a caret range.
#    It is exact. Use '^1.2.3' when you meant a range.
# 3. Editing poetry.lock by hand. It is generated; regenerate it.
# 4. Committing pyproject.toml while gitignoring poetry.lock. Every developer
#    and CI runner then resolves independently -> non-reproducible runs.
# 5. Forgetting `optional = true` on a group, then wondering why `poetry
#    install` pulls docs/mkdocs into every dev environment.
# 6. Expecting `poetry export` or `poetry shell` out of the box on Poetry 2+.
#    Both live in plugins now.
# 7. Using `package-mode = false` on a library you actually publish.
# 8. Expecting uv/poetry to speed anything up without a committed lockfile.
#    The speed comes from the pinned graph, not the tool.


